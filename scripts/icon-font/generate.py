#!/usr/bin/env python3
"""
Regenerate the Bungalow Icons webfont (ttf/woff/woff2), its CSS classes,
and the IconName union in icon.tsx, straight from
src/design-system/bungalow/icons.svg.

Usage (from the repo root):

    pip install -r scripts/icon-font/requirements.txt
    python3 scripts/icon-font/generate.py

See README.md in this folder for how to draw a new icon so this script
picks it up correctly.
"""
import json
import math
import re
import sys
from pathlib import Path

import svgelements as se
from shapely.geometry import LineString, Polygon, MultiPolygon
from shapely.ops import unary_union
from shapely.geometry.polygon import orient
from fontTools.ttLib import TTFont
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.pens.recordingPen import RecordingPen

REPO_ROOT = Path(__file__).resolve().parents[2]
SVG_PATH = REPO_ROOT / "src/design-system/bungalow/icons.svg"
DIGIT_FONT_PATH = REPO_ROOT / "src/design-system/bungalow/assets/fonts/bungalow-sans-bold.ttf"
FONT_OUT_DIR = REPO_ROOT / "src/design-system/bungalow/assets/fonts"
THEME_CSS_PATH = REPO_ROOT / "src/design-system/bungalow/styles/theme.css"
ICON_TSX_PATH = REPO_ROOT / "src/design-system/bungalow/components/icon.tsx"

FONT_FAMILY = "Bungalow Icons"
CLASS_PREFIX = "bungalow-icon"
FIRST_CODEPOINT = 0xE900

ROW_GAP = 50  # svg units; label y-gap that separates two icon rows
CLUSTER_PAD_CANDIDATES = [8, 10, 12, 15, 18, 20, 25]
MATCH_WARN_TOLERANCE = 40  # svg units; warn if a label sits this far outside its matched cluster

UPEM = 1000
TARGET_HEIGHT = 800
BASELINE_Y = -80
SIDE_BEARING = 40
SIMPLIFY_TOL = 0.12
CAP_STYLE_ROUND = 1
JOIN_STYLE_ROUND = 1

CSS_START = "/* bungalow-icons:start (generated by scripts/icon-font/generate.py - do not hand-edit) */"
CSS_END = "/* bungalow-icons:end */"
TSX_START = "  // bungalow-icons:start (generated by scripts/icon-font/generate.py - do not hand-edit)"
TSX_END = "  // bungalow-icons:end"


def slugify(name):
    s = name.strip().lower()
    s = re.sub(r"[^a-z0-9]+", "-", s)
    return s.strip("-")


# --------------------------------------------------------------- parsing --
def parse_svg():
    svg = se.SVG.parse(str(SVG_PATH))
    shapes, labels = [], []
    for e in svg.elements():
        tname = type(e).__name__
        if tname in ("Path", "Rect", "Circle", "Ellipse"):
            bb = e.bbox()
            if bb is None:
                continue
            shapes.append({"kind": tname, "bbox": bb, "elem": e})
        elif tname == "Text":
            txt = (e.text or "").strip()
            bb = e.bbox()
            if bb is None:
                continue
            if txt.replace(" ", "").isdigit():
                shapes.append({"kind": "Text", "bbox": bb, "elem": e, "text": txt})
            else:
                labels.append({"text": txt, "bbox": bb, "elem": e})
    return shapes, labels


def group_into_rows(shapes, labels):
    """Dynamically split labels (and the shapes above them) into rows, purely
    from vertical spacing - no hardcoded row count, so adding a 3rd row (or
    more icons in an existing row) just works.

    A shape is assigned to whichever row's label sits closest *below* it -
    icon art can sit anywhere from a few units to ~100 units above its own
    label, and rows can be packed tightly (a later row's icons sometimes
    start only a few units under the previous row's labels), so a fixed or
    midpoint-based cutoff between rows is not reliable; "nearest label
    below" is."""
    if not labels:
        raise SystemExit("No name labels found in icons.svg")
    labels_sorted = sorted(labels, key=lambda l: l["bbox"][1])
    rows = [[labels_sorted[0]]]
    for lab in labels_sorted[1:]:
        if lab["bbox"][1] - rows[-1][-1]["bbox"][1] > ROW_GAP:
            rows.append([])
        rows[-1].append(lab)
    row_label_y = [sum(l["bbox"][1] for l in row) / len(row) for row in rows]

    row_shapes = [[] for _ in rows]
    for s in shapes:
        y_bottom = s["bbox"][3]
        below = [i for i, ly in enumerate(row_label_y) if ly >= y_bottom]
        if below:
            row_i = min(below, key=lambda i: row_label_y[i] - y_bottom)
        else:
            # nothing below it (stray shape past the last row) - fall back
            # to the closest label overall rather than dropping it silently
            row_i = min(range(len(row_label_y)), key=lambda i: abs(row_label_y[i] - y_bottom))
        row_shapes[row_i].append(s)

    row_labels_sorted = [sorted(r, key=lambda l: l["bbox"][0]) for r in rows]
    return list(zip(row_shapes, row_labels_sorted))


def cluster_row(items, pad):
    n = len(items)
    parent = list(range(n))

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    def union(a, b):
        ra, rb = find(a), find(b)
        if ra != rb:
            parent[ra] = rb

    def intersects(b1, b2):
        x0a, y0a, x1a, y1a = b1
        x0b, y0b, x1b, y1b = b2
        return not (
            x1a + pad < x0b - pad
            or x1b + pad < x0a - pad
            or y1a + pad < y0b - pad
            or y1b + pad < y0a - pad
        )

    for i in range(n):
        for j in range(i + 1, n):
            if intersects(items[i]["bbox"], items[j]["bbox"]):
                union(i, j)
    groups = {}
    for i in range(n):
        groups.setdefault(find(i), []).append(items[i])
    return list(groups.values())


def best_cluster_for_row(row_shapes, target_count):
    """Try a few proximity thresholds and keep whichever gets closest to one
    cluster per label (icons vary in how tightly their sub-shapes pack)."""
    best = None
    for pad in CLUSTER_PAD_CANDIDATES:
        clusters = cluster_row(row_shapes, pad)
        score = abs(len(clusters) - target_count)
        if best is None or score < best[0]:
            best = (score, pad, clusters)
        if score == 0:
            break
    return best[1], best[2]


def match_row(row_shapes, row_labels, row_index):
    pad, clusters = best_cluster_for_row(row_shapes, len(row_labels))
    clusters = sorted(clusters, key=lambda c: min(s["bbox"][0] for s in c))

    if len(clusters) != len(row_labels):
        print(
            f"WARNING row {row_index}: {len(row_labels)} label(s) but {len(clusters)} icon "
            f"shape-cluster(s) found (best pad={pad}). Matching by nearest x position - "
            f"check the warnings below for anything that looks misaligned.",
            file=sys.stderr,
        )

    remaining = list(clusters)
    matched = []
    for label in row_labels:
        lx = label["bbox"][0]
        if not remaining:
            print(f"WARNING: no icon shapes left to match label {label['text']!r}", file=sys.stderr)
            continue
        centers = [
            (min(s["bbox"][0] for s in c) + max(s["bbox"][2] for s in c)) / 2 for c in remaining
        ]
        best_i = min(range(len(remaining)), key=lambda i: abs(centers[i] - lx))
        cluster = remaining.pop(best_i)
        cx0 = min(s["bbox"][0] for s in cluster)
        cx1 = max(s["bbox"][2] for s in cluster)
        if not (cx0 - MATCH_WARN_TOLERANCE <= lx <= cx1 + MATCH_WARN_TOLERANCE):
            print(
                f"WARNING: label {label['text']!r} at x={lx:.1f} is far from its matched "
                f"icon's x-range ({cx0:.1f}-{cx1:.1f}) in row {row_index} - double check icons.svg",
                file=sys.stderr,
            )
        matched.append((label, cluster))
    for cluster in remaining:
        cx0 = min(s["bbox"][0] for s in cluster)
        print(
            f"WARNING: icon shapes near x={cx0:.1f} in row {row_index} have no label under "
            f"them - skipped (add a <text> name below them)",
            file=sys.stderr,
        )
    return matched


# ------------------------------------------------------- stroke-to-fill --
def signed_area(ring):
    a = 0.0
    for i in range(len(ring) - 1):
        x1, y1 = ring[i]
        x2, y2 = ring[i + 1]
        a += x1 * y2 - x2 * y1
    return a / 2.0


def flatten_path(path_elem):
    rings = []
    cur = []
    for seg in path_elem:
        cls = type(seg).__name__
        if cls == "Move":
            if len(cur) >= 2:
                rings.append(cur)
            cur = [(seg.end[0], seg.end[1])]
        elif cls == "Close":
            if cur:
                cur.append((cur[0][0], cur[0][1]))
        elif cls == "Line":
            cur.append((seg.end[0], seg.end[1]))
        elif cls in ("CubicBezier", "QuadraticBezier", "Arc"):
            n = 24
            for i in range(1, n + 1):
                pt = seg.point(i / n)
                cur.append((pt[0], pt[1]))
    if len(cur) >= 2:
        rings.append(cur)
    return rings


def shape_to_geom(s):
    """The FILLED appearance of one raw SVG shape: strokes are expanded into
    real polygons (never left as zero-width centerlines) so overlapping or
    adjacent line art never 'mushes together' when the font fills it."""
    e = s["elem"]
    kind = s["kind"]
    stroke_w = getattr(e, "stroke_width", None) or 0
    stroke_col = getattr(e, "stroke", None)
    fill_col = getattr(e, "fill", None)
    has_stroke = stroke_col is not None and getattr(stroke_col, "value", True) is not None
    has_fill = fill_col is not None and getattr(fill_col, "value", True) is not None

    if kind == "Text":
        return text_geometry(e)

    def tp(pt):
        p = e.transform.point_in_matrix_space(pt)
        return (p[0], p[1])

    if kind == "Rect":
        x, y, w, h = e.x, e.y, e.width, e.height
        rings = [[tp(p) for p in [(x, y), (x + w, y), (x + w, y + h), (x, y + h), (x, y)]]]
    elif kind == "Circle":
        cx, cy, r = e.cx, e.cy, e.rx
        n = 96
        local = [(cx + r * math.cos(2 * math.pi * i / n), cy + r * math.sin(2 * math.pi * i / n)) for i in range(n + 1)]
        rings = [[tp(p) for p in local]]
    elif kind == "Ellipse":
        cx, cy, rx, ry = e.cx, e.cy, e.rx, e.ry
        n = 96
        local = [(cx + rx * math.cos(2 * math.pi * i / n), cy + ry * math.sin(2 * math.pi * i / n)) for i in range(n + 1)]
        rings = [[tp(p) for p in local]]
    elif kind == "Path":
        rings = flatten_path(e)
    else:
        return None

    polys = []
    for ring in rings:
        if len(ring) < 2:
            continue
        is_closed = ring[0] == ring[-1] and len(ring) >= 4
        if not has_stroke and has_fill:
            if is_closed:
                p = Polygon(ring)
                polys.append(p if p.is_valid else p.buffer(0))
            continue
        buf = LineString(ring).buffer(
            stroke_w / 2, cap_style=CAP_STYLE_ROUND, join_style=JOIN_STYLE_ROUND, quad_segs=16
        )
        polys.append(buf)
        if has_fill and is_closed:
            p = Polygon(ring)
            polys.append(p if p.is_valid else p.buffer(0))
    if not polys:
        return None
    return unary_union(polys)


# -------------------------------------------------- digit glyph handling --
_digit_font = TTFont(str(DIGIT_FONT_PATH))
_digit_upem = _digit_font["head"].unitsPerEm
_digit_cmap = _digit_font.getBestCmap()
_digit_glyf = _digit_font["glyf"]
_digit_hmtx = _digit_font["hmtx"]


def glyph_polygon(glyph_name):
    pen = RecordingPen()
    _digit_glyf[glyph_name].draw(pen, _digit_glyf)
    rings, cur = [], []
    for cmd, pts in pen.value:
        if cmd == "moveTo":
            cur = [pts[0]]
        elif cmd == "lineTo":
            cur.append(pts[0])
        elif cmd == "qCurveTo":
            p0 = cur[-1]
            end = pts[-1]
            ctrls = list(pts[:-1])
            p_start = p0
            for i, c in enumerate(ctrls):
                nxt_on = ((c[0] + ctrls[i + 1][0]) / 2, (c[1] + ctrls[i + 1][1]) / 2) if i < len(ctrls) - 1 else end
                a, b = p_start, c
                for t in [i / 8 for i in range(1, 9)]:
                    x = (1 - t) ** 2 * a[0] + 2 * (1 - t) * t * b[0] + t ** 2 * nxt_on[0]
                    y = (1 - t) ** 2 * a[1] + 2 * (1 - t) * t * b[1] + t ** 2 * nxt_on[1]
                    cur.append((x, y))
                p_start = nxt_on
        elif cmd == "curveTo":
            p0 = cur[-1]
            c1_, c2_, end = pts
            for t in [i / 12 for i in range(1, 13)]:
                x = (1 - t) ** 3 * p0[0] + 3 * (1 - t) ** 2 * t * c1_[0] + 3 * (1 - t) * t ** 2 * c2_[0] + t ** 3 * end[0]
                y = (1 - t) ** 3 * p0[1] + 3 * (1 - t) ** 2 * t * c1_[1] + 3 * (1 - t) * t ** 2 * c2_[1] + t ** 3 * end[1]
                cur.append((x, y))
        elif cmd == "closePath":
            if cur:
                rings.append(cur)
            cur = []
    return rings


def text_geometry(text_elem):
    """Digits baked as solid-minus-holes (so a '0' keeps its counter)."""
    scale_x = text_elem.transform.value_scale_x()
    scale_y = text_elem.transform.value_scale_y()
    font_size = text_elem.font_size * ((scale_x + scale_y) / 2)
    scale = font_size / _digit_upem
    anchor = text_elem.transform.point_in_matrix_space((text_elem.x, text_elem.y))
    pen_x = 0.0
    positive, negative = [], []
    for ch in text_elem.text:
        gname = _digit_cmap.get(ord(ch))
        if gname is None:
            continue
        for ring in glyph_polygon(gname):
            abs_ring = [(anchor[0] + (pen_x + gx) * scale, anchor[1] - gy * scale) for (gx, gy) in ring]
            if len(abs_ring) < 3:
                continue
            if abs_ring[0] != abs_ring[-1]:
                abs_ring.append(abs_ring[0])
            a = signed_area(abs_ring)
            (positive if a > 0 else negative).append(Polygon(abs_ring))
        pen_x += _digit_hmtx[gname][0]
    if not positive:
        return None
    solid = unary_union(positive)
    if negative:
        solid = solid.difference(unary_union(negative))
    return solid


def icon_geometry(cluster):
    geoms = []
    for s in cluster:
        g = shape_to_geom(s)
        if g is not None and not g.is_empty:
            geoms.append(g)
    if not geoms:
        return None
    merged = unary_union(geoms)
    return merged.simplify(SIMPLIFY_TOL, preserve_topology=True)


# ------------------------------------------------------------ font build --
def round_ring(ring, minx, maxy, scale):
    pts = []
    for (x, y) in ring:
        fx = (x - minx) * scale
        fy = (maxy - y) * scale + BASELINE_Y
        pts.append((round(fx), round(fy)))
    cleaned = [pts[0]]
    for p in pts[1:]:
        if p != cleaned[-1]:
            cleaned.append(p)
    if len(cleaned) >= 2 and cleaned[0] == cleaned[-1]:
        cleaned.pop()
    return cleaned


def build_font(icons):
    max_h = max(b[3] - b[1] for i in icons for b in [i["bounds"]])

    glyphs, metrics, codepoints, manifest = {}, {}, {}, []
    next_cp = FIRST_CODEPOINT
    for icon in icons:
        minx, miny, maxx, maxy = icon["bounds"]
        scale = TARGET_HEIGHT / max_h
        w_font = (maxx - minx) * scale

        geom = icon["geom"]
        polys = geom.geoms if isinstance(geom, MultiPolygon) else [geom]

        pen = TTGlyphPen(None)
        contour_count = 0
        for poly in polys:
            poly = orient(poly, sign=1.0)
            rings = [list(poly.exterior.coords)] + [list(r.coords) for r in poly.interiors]
            for ring in rings:
                pts = round_ring(ring, minx, maxy, scale)
                if len(pts) < 3:
                    continue
                if abs(signed_area(pts + [pts[0]])) < 4:
                    continue
                pen.moveTo(pts[0])
                for p in pts[1:]:
                    pen.lineTo(p)
                pen.closePath()
                contour_count += 1

        if contour_count == 0:
            print(f"WARNING: {icon['name']!r} produced no visible geometry - skipped", file=sys.stderr)
            continue

        glyph_name = icon["slug"]
        glyphs[glyph_name] = pen.glyph()
        adv = round(w_font) + 2 * SIDE_BEARING
        metrics[glyph_name] = (adv, SIDE_BEARING)
        codepoints[next_cp] = glyph_name
        manifest.append({"name": icon["name"], "slug": glyph_name, "codepoint": f"{next_cp:04x}"})
        next_cp += 1

    notdef_pen = TTGlyphPen(None)
    glyph_order = [".notdef"] + list(glyphs.keys())

    fb = FontBuilder(UPEM, isTTF=True)
    fb.setupGlyphOrder(glyph_order)
    fb.setupCharacterMap(codepoints)
    fb.setupGlyf({".notdef": notdef_pen.glyph(), **glyphs})
    fb.setupHorizontalMetrics({".notdef": (0, 0), **metrics})
    fb.setupHorizontalHeader(ascent=UPEM - 100, descent=-100)
    fb.setupNameTable(
        {
            "familyName": FONT_FAMILY,
            "styleName": "Regular",
            # Full and PostScript names too: Java's Font.createFont (the
            # bungalow desktop app) refuses a font without them.
            "fullName": FONT_FAMILY,
            "psName": FONT_FAMILY.replace(" ", "") + "-Regular",
            "uniqueFontIdentifier": FONT_FAMILY.replace(" ", "") + "-Regular",
        }
    )
    fb.setupOS2(sTypoAscender=UPEM - 100, sTypoDescender=-100, usWinAscent=UPEM, usWinDescent=100)
    fb.setupPost()

    FONT_OUT_DIR.mkdir(parents=True, exist_ok=True)
    ttf_path = FONT_OUT_DIR / "bungalow-icons.ttf"
    fb.save(str(ttf_path))

    for flavor in ("woff", "woff2"):
        tt = TTFont(str(ttf_path))
        tt.flavor = flavor
        tt.save(str(FONT_OUT_DIR / f"bungalow-icons.{flavor}"))

    return manifest


# ------------------------------------------------------ css / tsx output --
def write_css(manifest):
    css = THEME_CSS_PATH.read_text()
    if CSS_START not in css or CSS_END not in css:
        raise SystemExit(f"Could not find {CSS_START!r} markers in {THEME_CSS_PATH}")

    ordered = sorted(manifest, key=lambda m: m["slug"])
    rules = [
        f'[class^="{CLASS_PREFIX}-"]::before,',
        f'[class*=" {CLASS_PREFIX}-"]::before {{',
        f'  font-family: "{FONT_FAMILY}";',
        "  font-style: normal;",
        "  font-weight: normal;",
        "  line-height: 1;",
        "  display: inline-block;",
        "  -webkit-font-smoothing: antialiased;",
        "  -moz-osx-font-smoothing: grayscale;",
        "}",
    ]
    for m in ordered:
        rules.append(f'.{CLASS_PREFIX}-{m["slug"]}::before {{ content: "\\{m["codepoint"]}"; }}')

    block = CSS_START + "\n" + "\n".join(rules) + "\n" + CSS_END
    pattern = re.compile(re.escape(CSS_START) + r".*?" + re.escape(CSS_END), re.DOTALL)
    css = pattern.sub(lambda _match: block, css)
    THEME_CSS_PATH.write_text(css)


def write_manifest(manifest):
    """Name -> codepoint map next to the font, for consumers that can't read
    the CSS (native apps drawing glyphs straight from the .ttf)."""
    ordered = sorted(manifest, key=lambda m: m["slug"])
    data = {m["slug"]: m["codepoint"] for m in ordered}
    (FONT_OUT_DIR / "bungalow-icons.json").write_text(json.dumps(data, indent=2) + "\n")


def write_tsx(manifest):
    tsx = ICON_TSX_PATH.read_text()
    if TSX_START not in tsx or TSX_END not in tsx:
        raise SystemExit(f"Could not find {TSX_START!r} markers in {ICON_TSX_PATH}")

    ordered = sorted(manifest, key=lambda m: m["slug"])
    lines = [TSX_START] + [f'  | "{m["slug"]}"' for m in ordered] + [TSX_END]
    block = "\n".join(lines)
    pattern = re.compile(re.escape(TSX_START) + r".*?" + re.escape(TSX_END), re.DOTALL)
    tsx = pattern.sub(lambda _match: block, tsx)
    ICON_TSX_PATH.write_text(tsx)


# --------------------------------------------------------------------- --
def main():
    shapes, labels = parse_svg()
    rows = group_into_rows(shapes, labels)
    print(f"Found {len(rows)} row(s), {len(labels)} label(s) total.")

    icons = []
    for row_index, (row_shapes, row_labels) in enumerate(rows):
        for label, cluster in match_row(row_shapes, row_labels, row_index):
            name = label["text"]
            geom = icon_geometry(cluster)
            if geom is None or geom.is_empty:
                print(f"WARNING: {name!r} produced no fillable geometry - skipped", file=sys.stderr)
                continue
            minx, miny, maxx, maxy = geom.bounds
            icons.append({"name": name, "slug": slugify(name), "geom": geom, "bounds": (minx, miny, maxx, maxy)})

    slugs_seen = {}
    for icon in icons:
        slugs_seen.setdefault(icon["slug"], []).append(icon["name"])
    for slug, names in slugs_seen.items():
        if len(names) > 1:
            raise SystemExit(f"Duplicate icon slug {slug!r} from labels {names} - rename one of them")

    print(f"Matched {len(icons)} icon(s), building font...")
    manifest = build_font(icons)
    print(f"Built {len(manifest)} glyph(s).")

    write_css(manifest)
    write_tsx(manifest)
    write_manifest(manifest)
    print(f"Updated {THEME_CSS_PATH.relative_to(REPO_ROOT)} and {ICON_TSX_PATH.relative_to(REPO_ROOT)}.")


if __name__ == "__main__":
    main()
